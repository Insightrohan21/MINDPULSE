-- MindPulse 2.0 initial schema
create table if not exists public.heart_readings (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  bpm integer not null check (bpm between 25 and 240),
  spo2 numeric(5,2) check (spo2 between 0 and 100),
  recorded_at timestamptz not null default now(),
  source text not null default 'watch'
);
create index if not exists heart_readings_user_time_idx on public.heart_readings(user_id, recorded_at desc);

create table if not exists public.activity_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  activity_type text not null default 'movement',
  duration_minutes integer not null default 0 check (duration_minutes >= 0),
  steps integer check (steps >= 0),
  recorded_at timestamptz not null default now()
);
create index if not exists activity_logs_user_time_idx on public.activity_logs(user_id, recorded_at desc);

create table if not exists public.daily_tasks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 240),
  completed boolean not null default false,
  task_date date not null default current_date,
  created_at timestamptz not null default now()
);
create index if not exists daily_tasks_user_date_idx on public.daily_tasks(user_id, task_date desc);

create table if not exists public.journal_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  body text not null,
  mood text,
  created_at timestamptz not null default now()
);
create index if not exists journal_entries_user_time_idx on public.journal_entries(user_id, created_at desc);

alter table public.heart_readings enable row level security;
alter table public.activity_logs enable row level security;
alter table public.daily_tasks enable row level security;
alter table public.journal_entries enable row level security;

create policy "Users manage own heart readings" on public.heart_readings for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage own activity logs" on public.activity_logs for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage own daily tasks" on public.daily_tasks for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage own journal entries" on public.journal_entries for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);
